/* Line numbers + linkable lines for Documenter code blocks — interactions only.
 *
 * The build-time plugin (DocumenterCodeBlocks.jl) has already emitted the split
 * markup statically:
 *
 *   <pre id="c-1a2b3c4d"><code class="… line-numbers"><span class="code-lines">
 *     <span class="line"><span class="line-num" aria-hidden="true"></span>…</span>…
 *   </span></code></pre>
 *
 * Line numbers render from CSS counters with zero JS. This script only adds the
 * client-side interactions: the whole-block permalink button, gutter
 * click/shift-click/drag selection, and hash restore.
 *
 * Hash formats:  #c-1a2b3c4d          whole block
 *                #c-1a2b3c4d-L5       single line
 *                #c-1a2b3c4d-L5-L10   line range
 *
 * L-numbers are the DISPLAYED line numbers. A block whose numbering continues
 * from earlier blocks on the page (`@codeblocks line_counter = :continue`)
 * carries data-ln-start on its .code-lines wrapper; internally everything is
 * a 1-based child index, converted at the hash boundary.
 */
(function () {
  "use strict";

  // Block ids are content hashes: c-<8 hex>, with -2/-3 … for same-page dupes.
  const HASH_RE = /^#(c-[0-9a-f]+(?:-\d+)?)(?:-L(\d+)(?:-L(\d+))?)?$/;

  const LINK_SVG =
    '<svg viewBox="0 0 640 512" fill="currentColor" aria-hidden="true">' +
    '<path d="M579.8 267.7c56.5-56.5 56.5-148 0-204.5c-50-50-128.8-56.5-186.3-15.4l-1.6 1.1c-14.4 10.3-17.7 30.3-7.4 44.6s30.3 17.7 44.6 7.4l1.6-1.1c32.1-22.9 76-19.3 103.8 8.6c31.5 31.5 31.5 82.5 0 114L422.3 334.8c-31.5 31.5-82.5 31.5-114 0c-27.9-27.9-31.5-71.8-8.6-103.8l1.1-1.6c10.3-14.4 6.9-34.4-7.4-44.6s-34.4-6.9-44.6 7.4l-1.1 1.6C206.5 251.2 213 330 263 380c56.5 56.5 148 56.5 204.5 0L579.8 267.7zM60.2 244.3c-56.5 56.5-56.5 148 0 204.5c50 50 128.8 56.5 186.3 15.4l1.6-1.1c14.4-10.3 17.7-30.3 7.4-44.6s-30.3-17.7-44.6-7.4l-1.6 1.1c-32.1 22.9-76 19.3-103.8-8.6C74 372 74 321 105.5 289.5L217.7 177.2c31.5-31.5 82.5-31.5 114 0c27.9 27.9 31.5 71.8 8.6 103.9l-1.1 1.6c-10.3 14.4-6.9 34.4 7.4 44.6s34.4 6.9 44.6-7.4l1.1-1.6C433.5 260.8 427 182 377 132c-56.5-56.5-148-56.5-204.5 0L60.2 244.3z"/></svg>';

  let anchor = null; // { pre, line } from the last plain gutter click
  let drag = null; // { pre, wrap, start } while a gutter drag is in progress
  let suppressClick = false; // swallow the click generated by a finished drag

  // ---- setup ------------------------------------------------------------

  function addPermalinks() {
    document.querySelectorAll('article pre[id^="c-"]').forEach(function (pre) {
      const btn = document.createElement("button");
      btn.className = "block-link";
      btn.setAttribute("aria-label", "Link to this code block");
      btn.title = "Link to this code block";
      btn.innerHTML = LINK_SVG;
      btn.addEventListener("click", function () {
        setHash("#" + pre.id);
      });
      pre.appendChild(btn);
    });
  }

  function armGutters() {
    document.querySelectorAll("article pre .code-lines").forEach(function (wrap) {
      wrap.addEventListener("mousedown", onGutterMouseDown);
    });
  }

  // ---- gutter interactions ---------------------------------------------

  // First displayed line number of the block (data-ln-start, default 1).
  function lnStart(pre) {
    const wrap = pre.querySelector(".code-lines");
    const start = wrap && wrap.dataset.lnStart ? parseInt(wrap.dataset.lnStart, 10) : 1;
    return isNaN(start) ? 1 : start;
  }

  // `a`/`b` are 1-based child indices; the hash carries displayed numbers.
  function rangeHash(pre, a, b) {
    const off = lnStart(pre) - 1;
    a += off;
    b += off;
    return a === b ? "#" + pre.id + "-L" + a : "#" + pre.id + "-L" + a + "-L" + b;
  }

  function onGutterMouseDown(e) {
    if (e.button !== 0) return;
    // The gutter cell is a real element, so a plain target check suffices —
    // no geometry math (which was engine-dependent for pseudo-elements).
    const num = e.target.closest(".line-num");
    if (!num) return;
    const span = num.parentElement;
    const pre = span.closest("pre");
    const wrap = span.parentElement;
    const line = Array.prototype.indexOf.call(wrap.children, span) + 1;
    if (e.shiftKey && anchor && anchor.pre === pre) {
      const a = Math.min(anchor.line, line);
      const b = Math.max(anchor.line, line);
      setHash(rangeHash(pre, a, b));
    } else {
      drag = { pre: pre, wrap: wrap, start: line };
      highlightRange(pre, line, line);
    }
    e.preventDefault(); // no native text selection while interacting with the gutter
  }

  function lineFromPointer(wrap, clientY) {
    const children = wrap.children;
    if (clientY <= children[0].getBoundingClientRect().top) return 1;
    for (let i = 0; i < children.length; i++) {
      if (clientY < children[i].getBoundingClientRect().bottom) return i + 1;
    }
    return children.length; // below the block: clamp to the last line
  }

  function onDragMove(e) {
    if (!drag) return;
    const line = lineFromPointer(drag.wrap, e.clientY);
    highlightRange(drag.pre, Math.min(drag.start, line), Math.max(drag.start, line));
  }

  function onDragEnd(e) {
    if (!drag) return;
    const line = lineFromPointer(drag.wrap, e.clientY);
    const a = Math.min(drag.start, line);
    const b = Math.max(drag.start, line);
    anchor = { pre: drag.pre, line: drag.start }; // shift-click extends from here
    setHash(rangeHash(drag.pre, a, b));
    drag = null;
    suppressClick = true; // the drag's own click event must not deselect
  }

  // Clicking outside the SELECTED code block clears an active line/block
  // selection (highlight + the #c-… fragment) — including clicks inside a
  // *different* code block. A click inside the selected block itself — links,
  // text selection, the gutter — leaves it alone, and so does the click that
  // ends a gutter drag: when the pointer is released outside the block, the
  // browser fires the click on the common ancestor (outside the pre), so
  // onDragEnd raises a one-shot suppress flag. (Gutter interactions in another
  // block are also drags, so their clicks are suppressed too and the new
  // selection they just made survives this handler.)
  function onDocumentClick(e) {
    if (suppressClick) {
      suppressClick = false;
      return;
    }
    const m = HASH_RE.exec(location.hash);
    if (!m) return;
    const pre = e.target.closest('pre[id^="c-"]');
    if ((pre && pre.id === m[1]) || e.target.closest(".ref-popup")) return;
    clearHighlights();
    anchor = null;
    history.replaceState(null, "", location.pathname + location.search);
  }

  // ---- hash handling ----------------------------------------------------

  function setHash(hash) {
    history.replaceState(null, "", hash); // no native scroll jump, no history spam
    applyHash(hash, false);
  }

  function clearHighlights() {
    document.querySelectorAll(".line.hl").forEach(function (el) {
      el.classList.remove("hl");
    });
    document.querySelectorAll("pre.hl-block").forEach(function (el) {
      el.classList.remove("hl-block");
    });
  }

  function highlightRange(pre, a, b) {
    clearHighlights();
    const lines = pre.querySelectorAll(".line");
    // Clamp: a stale hash (e.g. numbering offsets changed) must not throw.
    for (let n = Math.max(a, 1); n <= b && n <= lines.length; n++) {
      lines[n - 1].classList.add("hl");
    }
  }

  function applyHash(hash, scroll) {
    clearHighlights();
    const m = HASH_RE.exec(hash || "");
    if (!m) return;
    const pre = document.getElementById(m[1]);
    if (!pre) return;
    if (!m[2]) {
      pre.classList.add("hl-block");
      if (scroll) pre.scrollIntoView({ block: "center" });
      return;
    }
    // Hash numbers are displayed numbers; convert to child indices.
    const off = lnStart(pre) - 1;
    const a = Math.min(+m[2], m[3] ? +m[3] : +m[2]) - off;
    const b = Math.max(+m[2], m[3] ? +m[3] : +m[2]) - off;
    highlightRange(pre, a, b);
    const lines = pre.querySelectorAll(".line");
    if (scroll && lines[a - 1]) lines[a - 1].scrollIntoView({ block: "center" });
  }

  // ---- init -------------------------------------------------------------

  function init() {
    addPermalinks();
    armGutters();
    document.addEventListener("mousemove", onDragMove);
    document.addEventListener("mouseup", onDragEnd);
    document.addEventListener("click", onDocumentClick);
    applyHash(location.hash, true); // restore + scroll on load
    window.addEventListener("hashchange", function () {
      applyHash(location.hash, true);
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
